document.addEventListener('DOMContentLoaded', function() {
  const btns = document.querySelectorAll('.btn-register');
  btns.forEach(btn => {
    btn.addEventListener('click', function() {
      const webinarId = this.getAttribute('data-id');
      const originalHtml = this.innerHTML;
      this.disabled = true;
      this.innerHTML = '<span class="spinner-border spinner-border-sm"></span>';
      
      fetch('<?= base_url('webinars/register/') ?>' + webinarId, {
        method: 'POST',
        headers: {
          'X-Requested-With': 'XMLHttpRequest',
          '<?= csrf_header() ?>': '<?= csrf_hash() ?>'
        }
      })
      .then(response => response.json())
      .then(data => {
        if (data.status === 201 || !data.error) {
          this.classList.remove('btn-primary');
          this.classList.add('btn-success');
          this.innerHTML = 'Registered';
          alert(data.message || 'Successfully registered!');
        } else {
          alert(data.messages ? data.messages.error : (data.message || 'An error occurred'));
          this.disabled = false;
          this.innerHTML = originalHtml;
        }
      })
      .catch(error => {
        alert('An error occurred. Please try again.');
        this.disabled = false;
        this.innerHTML = originalHtml;
      });
    });
  });
});

function handleSub(e) {
  e.preventDefault();
  const form = e.target;
  const btn = form.querySelector('button[type="submit"]');
  const email = form.querySelector('input[type="email"]').value;
  const name = form.querySelector('input[type="text"]').value;
  const originalHtml = btn.innerHTML;
  
  btn.disabled = true;
  btn.innerHTML = '<span class="spinner-border spinner-border-sm"></span>';
  
  const formData = new FormData();
  formData.append('email', email);
  formData.append('name', name);
  
  fetch('<?= base_url('newsletter/subscribe') ?>', {
    method: 'POST',
    body: formData,
    headers: {
      'X-Requested-With': 'XMLHttpRequest',
      '<?= csrf_header() ?>': '<?= csrf_hash() ?>'
    }
  })
  .then(response => response.json())
  .then(data => {
    if (data.status === 201 || data.status === 200 || !data.error) {
      alert(data.message || 'Successfully subscribed!');
      form.reset();
    } else {
      alert(data.messages ? data.messages.error : (data.message || 'An error occurred'));
    }
  })
  .catch(error => {
    alert('An error occurred. Please try again.');
  })
  .finally(() => {
    btn.disabled = false;
    btn.innerHTML = originalHtml;
  });
}
